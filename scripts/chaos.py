# ---- runner ------------------------------------------------------------------------------------

def run_fault(name: str, workdir: Path) -> Result:
    """One fault on a fresh throwaway database, with the fixture reset and no keys. Restores the
    database binding, the keys and the fault registry afterwards, whatever happened."""
    r = Result(fault=name, inject=INJECT[name])
    url_before = db.url()
    keys_before = (config.RAZORPAY_KEY_ID, config.RAZORPAY_KEY_SECRET, config.ANTHROPIC_API_KEY)
    config.RAZORPAY_KEY_ID = config.RAZORPAY_KEY_SECRET = config.ANTHROPIC_API_KEY = ""
    faults.clear()
    razorpay_client.reset_fixture()
    path = workdir / f"{name}.db"
    for suffix in ("", "-journal"):
        Path(str(path) + suffix).unlink(missing_ok=True)
    db.configure(f"sqlite:///{path}")
    session = None
    try:
        db.init_db()
        faults.activate(name)
        session = db.session()
        SCENARIOS[name](r, session, [])
    except Exception as exc:  # one broken scenario must not hide the other eight
        r.error = f"{type(exc).__name__}: {exc}"
    finally:
        if session is not None:
            session.close()
        faults.clear()
        razorpay_client.reset_fixture()
        db.configure(url_before)
        config.RAZORPAY_KEY_ID, config.RAZORPAY_KEY_SECRET, config.ANTHROPIC_API_KEY = keys_before
    return r


def run_all(names, workdir: Path) -> list[Result]:
    return [run_fault(n, workdir) for n in names]


# ---- rendering ---------------------------------------------------------------------------------

def render_text(r: Result) -> str:
    lines = [f"FAULT {r.fault}", f"  inject      : {r.inject}"]
    lines += [f"  event       : {e}" for e in r.events]
    for t in r.traces:
        label = f"   [{t.label}]" if len(r.traces) > 1 else ""
        lines.append(f"  path        : {t.path()}{label}")
        lines += [f"      {stage:<9} {_clip(_relative(msg))}" for stage, msg in t.trail]
    lines.append(f"  fallback    : {r.fallback}")
    lines.append(f"  final state : {r.final_state}")
    lines += [f"  {'check ok   ' if ok else 'CHECK FAIL '}: {what}" for ok, what in r.checks]
    if r.error:
        lines.append(f"  error       : {r.error}")
    lines.append(f"  verdict     : {r.verdict}  {INVARIANT[r.fault]}")
    return "\n".join(lines)


def render_summary(results: list[Result]) -> str:
    headers = ["fault", "injected at", "fallback", "final state", "verdict"]
    rows = [[r.fault, INJECTED_AT[r.fault], _clip(r.fallback, 70), r.summary, r.verdict] for r in results]
    widths = [max(len(h), *(len(row[i]) for row in rows)) for i, h in enumerate(headers)]
    fmt = lambda cells: "  ".join(c.ljust(w) for c, w in zip(cells, widths)).rstrip()  # noqa: E731
    passed = sum(1 for r in results if r.passed)
    body = [fmt(headers), fmt(["-" * w for w in widths])] + [fmt(row) for row in rows]
    return "\n".join(["SUMMARY"] + body + [f"{len(results)} faults: {passed} PASS, {len(results) - passed} FAIL"])


def render_markdown(results: list[Result]) -> str:
    md = [
        "# Failure report",
        "",
        "Generated by `scripts/chaos.py --all --write docs/failure_report.md`; re-run with `make chaos`. "
        "Every fault in `app/faults.py` is injected at the client boundary where it would happen in production "
        "(the LLM client, the Razorpay client, the database engine, the event source), and a real event is run "
        "through the real pipeline. The run is deterministic and offline: a throwaway SQLite file per fault, the "
        "in-memory Razorpay fixture, no LLM key, a fixed clock (timestamps are offsets from T0) and injected "
        "sleeps (backoff waits are recorded, not slept). Nothing here touches the network, and the file is "
        "reproducible byte for byte.",
        "",
        "How to read a section: **inject** is what was broken; **path** is the stage sequence taken, from the "
        "audit rows the run actually wrote; **fallback** is the degrade the code chose; **final state** is what "
        "the database holds afterwards; **checks** are the invariants asserted, and the script exits non-zero if "
        "any of them fails.",
        "",
        "## Summary",
        "",
        "| # | fault | injected at | fallback | final state | verdict |",
        "|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(results, 1):
        md.append(f"| {i} | `{r.fault}` | {INJECTED_AT[r.fault]} | {r.fallback} | {r.summary} | **{r.verdict}** |")
    passed = sum(1 for r in results if r.passed)
    md += ["", f"{len(results)} faults: {passed} PASS, {len(results) - passed} FAIL.", ""]

    for i, r in enumerate(results, 1):
        md += [f"## {i}. {r.fault}", "", f"**Inject:** {r.inject}", ""]
        md += [f"**Event:** {e}  " for e in r.events]
        md.append("")
        for t in r.traces:
            label = f" ({t.label})" if len(r.traces) > 1 else ""
            md += [f"**Path{label}:** `{t.path()}`", "", "```text"]
            md += [f"{stage:<9} {_clip(_relative(msg))}" for stage, msg in t.trail]
            md += ["```", ""]
        md += [f"**Fallback:** {r.fallback}", "", f"**Final state:** {r.final_state}", "", "**Checks:**"]
        md += [f"- {'ok' if ok else 'FAIL'}: {what}" for ok, what in r.checks]
        if r.error:
            md.append(f"- error: {r.error}")
        md += ["", f"**Verdict:** {r.verdict} ({INVARIANT[r.fault]})", "",
               f"**Why this is the right degrade for a money path:** {WHY[r.fault]}", ""]

    md += [
        "## What this report does not cover",
        "",
        "- The live HTTP paths (`LiveRazorpayClient`, `AnthropicLLM`) are not exercised: the faults are injected "
        "one layer below them, on the same interfaces they implement, so the pipeline's handling is what is tested, "
        "not the wire format of a real 429 or a real API timeout.",
        "- Two processes executing the same pending job at the same instant are not simulated; the single-process "
        "scheduler makes that impossible here, and the Razorpay `reference_id` guard shown under `db_unavailable` "
        "is what would catch it.",
        "- The `reference_id` uniqueness at Razorpay, the lookup by `reference_id` (`GET /payment_links?"
        "reference_id=`) that the reconcile step and the crash probes rely on, the shape of "
        "`POST /payment_links/{id}/cancel` and of `GET /orders/{id}/payments` that `order_paid_elsewhere` relies on, "
        "are assumptions stated in `FixtureRazorpayClient`. If the real API accepted duplicates, the worst case in the crash-after-send probe "
        "would be a redundant link, never a second charge, because a Payment Link only collects money when a "
        "customer chooses to pay it; if the lookup answered differently, the reconcile step reports `unknown` and "
        "parks the payment for a person instead of minting a follow-up.",
        "",
    ]
    return "\n".join(md)


# ---- entrypoint -------------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python scripts/chaos.py", description=__doc__.split("\n\n")[0])
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--fault", choices=faults.FAULTS, help="inject one fault")
    g.add_argument("--all", action="store_true", help="inject every fault in turn and print a summary")
    p.add_argument("--write", metavar="PATH", help="with --all: also write the report as Markdown to PATH")
    args = p.parse_args(argv)
    if args.write and not args.all:
        p.error("--write needs --all: the report covers every fault or none")

    names = list(faults.FAULTS) if args.all else [args.fault]
    workdir = Path(tempfile.mkdtemp(prefix="pra-chaos-"))
    print("payment-recovery-agent chaos harness")
    print(f"  faults   : {', '.join(names)}")
    print(f"  database : throwaway SQLite per fault under {workdir} (never ./recovery.db)")
    print("  razorpay : in-memory fixture (RAZORPAY_KEY_ID forced empty for this run); razorpay_* faults wrap it")
    print("  llm      : none (ANTHROPIC_API_KEY forced empty for this run); llm_* faults inject FaultingLLM")
    print("  clock    : fixed T0; timestamps print as offsets; backoff sleeps are recorded, not waited")
    try:
        results = []
        for name in names:
            r = run_fault(name, workdir)
            results.append(r)
            print()
            print(render_text(r))
        if args.all:
            print()
            print(render_summary(results))
        if args.write:
            out = Path(args.write)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(render_markdown(results), encoding="utf-8")
            print(f"wrote {out}")
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    return 0 if all(r.passed for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
