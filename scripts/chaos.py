    r.check(s2["job_status"] == "no_action" and "pay_ChaosElsewhere02" in (s2["last_error"] or "")
            and _order_checks(fx) == 1 and _creates(fx) == 0 and fx.links() == [],
            "order check: one GET /orders/{id}/payments, a captured payment found, no_action, zero creates, zero links")
    r.check(a2.paid_by_payment_id == "pay_ChaosElsewhere02" and o2 is not None and o2.note == executor.ORDER_PAID_NOTE,
            "the check's finding is recorded on the attempt and the outcome is written")
    r.traces.append(Trace("(2) order-check probe", _trail(session, s2["attempt_id"])))

    # (3) paid after the link was sent
    ev3 = _event(FailureClass.HARD_DECLINE, 0)  # delay 0: the link goes out at T0
    r.events.append(_describe_event(ev3) + "  [link sent at T0; the order is paid at T0+2h]")
    s3 = _deliver(session, ev3, now=T0, rz=rz, lm=lm, sleeps=sleeps, execute_now=False)
    r.check(s3["job_status"] == "sent" and len(fx.links()) == 1, "delivery: link created and sent at T0")
    paid3 = _captured_payload(ev3["order_id"], "pay_ChaosElsewhere03", ev3["amount_paise"], T0 + timedelta(hours=2))
    out3 = ingest.ingest_event(session, paid3, now=T0 + timedelta(hours=2), rz_client=rz, event_id="evt_chaos_captured_3")
    job3 = session.get(RecoveryJob, s3["job_id"])
    o3 = _outcome(session, s3["attempt_id"])
    link3 = fx.fetch_payment_link(job3.razorpay_link_id)
    r.check(out3["cancelled"] == [job3.id] and out3["voided"] == [] and out3["parked"] == [],
            "payment.captured at T0+2h: the live link's job is the one cancelled")
    r.check(_cancels(fx) == 1 and link3["status"] == "cancelled",
            "exactly one POST /payment_links/{id}/cancel; the link is 'cancelled' at the fixture")
    r.check(job3.status == "cancelled" and "order already paid by pay_ChaosElsewhere03" in (job3.last_error or ""),
            "job status cancelled, last_error names the paying payment")
    r.check(o3 is not None and o3.recovered is False and o3.amount_recovered_paise == 0
            and o3.note.startswith(executor.ORDER_PAID_NOTE) and job3.razorpay_link_id in o3.note,
            "outcome written: not recovered, amount 0, note says the link was cancelled")
    r.check(pipeline.open_link_jobs(session) == [] and pipeline.poll_outcomes(session, rz_client=rz, now=T0 + timedelta(hours=3)) == [],
            "the cancelled link is no longer open: poll has nothing to ask about")
    again = ingest.ingest_event(session, paid3, now=T0 + timedelta(hours=2, minutes=1), rz_client=rz, event_id="evt_chaos_captured_3")
    outcomes3 = session.execute(select(Outcome).where(Outcome.job_id == job3.id)).scalars().all()
    r.check(again["already_recorded"] is True and again["cancelled"] == [] and _cancels(fx) == 1 and len(outcomes3) == 1,
            "redelivered payment.captured: recorded as such, no second cancel call, no second outcome")
    r.traces.append(Trace("(3) paid after the link was sent", _trail(session, s3["attempt_id"])))

    # (4) the cancel is refused
    ev4 = _event(FailureClass.NETWORK_TIMEOUT, 1)  # upi, no token: link path
    r.events.append("cancel-refused probe (Razorpay answers 502 to the cancel): " + _describe_event(ev4) + "  [execute_now]")
    s4 = _deliver(session, ev4, now=T0, rz=rz, lm=lm, sleeps=sleeps, execute_now=True)
    refusing = _CancelRefused(fx)
    paid4 = _captured_payload(ev4["order_id"], "pay_ChaosElsewhere04", ev4["amount_paise"], T0 + timedelta(hours=1))
    out4 = ingest.ingest_event(session, paid4, now=T0 + timedelta(hours=1), rz_client=refusing, event_id="evt_chaos_captured_4")
    job4 = session.get(RecoveryJob, s4["job_id"])
    o4 = _outcome(session, s4["attempt_id"])
    link4 = fx.fetch_payment_link(job4.razorpay_link_id)
    r.check(s4["job_status"] == "sent" and out4["parked"] == [job4.id] and out4["cancelled"] == [] and refusing.cancel_calls == 1,
            "the cancel was attempted once and refused (502); the job is reported parked, not cancelled")
    r.check(job4.status == "human_queue" and "cancelling live link" in (job4.last_error or "") and "502" in (job4.last_error or ""),
            "job human_queue; last_error says the link is still live and why the cancel failed")
    r.check(o4 is not None and not o4.recovered and o4.note.startswith("human_queue") and "a person cancels" in o4.note,
            "outcome written: human_queue, a person cancels the link")
    r.check(link4["status"] == "created" and _cancels(fx) == 1,
            "the link really is still live at the fixture (only the earlier probe's cancel reached it): the trail says so, nothing is silent")
    r.traces.append(Trace("(4) cancel refused", _trail(session, s4["attempt_id"])))

    r.fallback = ("paid before execution: pending job voided (no_action + outcome), execute refuses, zero links; a stale "
                  "payment.failed for the order is refused at schedule; the pre-send order check catches an unreported "
                  "payment; paid after sending: one cancel call, job cancelled + outcome; cancel refused: human_queue with "
                  "the reason")
    r.final_state = (f"(1) job#{job.id} no_action, links=0, calls=0, outcome '{executor.ORDER_PAID_NOTE}'; "
                     f"(1b) stale job#{s_stale['job_id']} no_action at schedule; "
                     f"(2) job#{s2['job_id']} no_action after 1 order check, links=0; "
                     f"(3) job#{job3.id} cancelled, link {job3.razorpay_link_id} cancelled at Razorpay, 1 cancel call, outcome written; "
                     f"(4) job#{job4.id} human_queue (cancel 502), link {job4.razorpay_link_id} still live and flagged")
    r.summary = "0 links before; 1 cancel after"


