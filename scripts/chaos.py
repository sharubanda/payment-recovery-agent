class _LostResponseClient:
    """The request lands (the fixture creates the link) but no HTTP answer ever comes back, on
    every attempt: the classic lost-response timeout that a naive retry turns into two links."""
    name = "lost-response"

    def __init__(self, inner: FixtureRazorpayClient):
        self.inner = inner

    def create_payment_link(self, payload: dict) -> dict:
        try:
            self.inner.create_payment_link(payload)
        except RazorpayError as exc:  # a retry of the same reference_id also lands and also gets no answer
            if "already exists" not in exc.description:
                raise
        raise RazorpayError(0, "NETWORK", "TimeoutError: the request was sent; the response never arrived")

    def fetch_payment_link(self, link_id: str) -> dict:
        return self.inner.fetch_payment_link(link_id)

    def list_payment_links(self, *, reference_id: str) -> list[dict]:
        return self.inner.list_payment_links(reference_id=reference_id)


def _probe_crash_after_send(r: Result, s3, fx: FixtureRazorpayClient, rz, lm, sleeps: list) -> RecoveryJob:
    """The request reached Razorpay, then the process died before writing status=sent."""
    ev2 = _event(FailureClass.ISSUER_DOWN, 1)
    r.events.append("crash-after-send probe: " + _describe_event(ev2))
    links_before = len(fx.links())
    s4 = _deliver(s3, ev2, now=T0 + timedelta(minutes=5), rz=rz, lm=lm, sleeps=sleeps, execute_now=False)
    job = s3.get(RecoveryJob, s4["job_id"])
    a2 = s3.get(PaymentAttempt, s4["attempt_id"])
    r.check(job.status == "pending", "crash probe: the pending job row is committed with its key before anything goes out")
    created = fx.create_payment_link(executor.build_payment_link_payload(a2, job, "ISSUER_DOWN", now=T0 + timedelta(minutes=5)))
    job.attempts_made = 1  # what the row looks like after such a crash: the counter is committed before the call
    s3.commit()
    job = executor.execute_job(s3, job, client=rz, now=T0 + timedelta(minutes=20), sleep=sleeps.append)
    r.traces.append(Trace("crash-after-send probe (link created, 'sent' never written, pending job re-run)",
                          _trail(s3, a2.id)))
    r.check(job.status == "sent" and job.razorpay_link_id == created["id"] and job.razorpay_link_url == created["short_url"]
            and "already exists" in (job.last_error or ""),
            "re-running the pending job: Razorpay rejects the duplicate reference_id -> the existing link is looked up "
            "by that reference_id and recorded on the job (id and short_url), nothing re-created")
    r.check(len(fx.links()) == links_before + 1 and len(_jobs(s3, a2.id)) == 1,
            "one link and one job for this payment; the repeat for the same reference_id was rejected, not fulfilled")
    r.check(created["id"] in [j.razorpay_link_id for j in pipeline.open_link_jobs(s3)],
            "the recovered link is visible to poll, so a customer payment on it will be recorded")
    return job


def _probe_lost_response(r: Result, s3, fx: FixtureRazorpayClient, lm, sleeps: list) -> RecoveryJob:
    """The request reached Razorpay on every attempt, but no answer ever came back."""
    ev3 = _event(FailureClass.AUTH_ABANDONED, 2)
    r.events.append("lost-response probe: " + _describe_event(ev3) + "  [execute_now]")
    links_before = len(fx.links())
    lost = _LostResponseClient(fx)
    s5 = _deliver(s3, ev3, now=T0 + timedelta(minutes=5), rz=lost, lm=lm, sleeps=sleeps, execute_now=True)
    job = s3.get(RecoveryJob, s5["job_id"])
    rows = _audit_rows(s3, s5["attempt_id"])
    r.traces.append(Trace("lost-response probe (every attempt lands, no answer arrives, then reconcile)",
                          [(x.stage, x.message) for x in rows]))
    reconciled = [x for x in rows if x.stage == "reconcile"]
    r.check(job.attempts_made == executor.MAX_HTTP_ATTEMPTS and any("transport" in x.message for x in rows if x.stage == "execute"),
            "lost-response probe: three attempts under one reference_id, each a transport failure (kind transport)")
    r.check(len(reconciled) == 1 and "had landed" in reconciled[0].message,
            "lost-response probe: the failure is ambiguous, so the job was reconciled by reference_id before any "
            "follow-up: the link was found")
    r.check(job.status == "sent" and job.razorpay_link_id is not None and job.razorpay_link_url in (job.nudge_body or ""),
            "lost-response probe: job marked sent with the recovered link, nudge drafted with its short_url")
    r.check(len(fx.links()) == links_before + 1 and len(_jobs(s3, s5["attempt_id"])) == 1 and s5["followup_job_id"] is None,
            "lost-response probe: exactly one link and one job; no follow-up minted under a second key")
    return job


def scenario_db_unavailable(r: Result, session, sleeps: list) -> None:
    """Four steps: the write refused before anything went out; the redelivery once the database is
    back; and two probes of the mirror case, state lost after the request went out (a 'sent' write
    that never happened, and an HTTP answer that never arrived)."""
    good_url = db.url()
    rz = razorpay_client.get_client()
    fx = razorpay_client.fixture()
    lm = llm.get_client()
    ev = _event(FailureClass.INSUFFICIENT_FUNDS, 0)
    r.events.append(_describe_event(ev))

    attempt = _ingest(session, ev, T0)  # the event exists durably; the outage starts after this
    attempt_id = attempt.id
    session.close()

    db.configure(BROKEN_DB_URL)
    broken = db.session()
    error = None
    try:
        process_attempt(broken, attempt, execute_now=True, now=T0, rz_client=rz, llm_client=lm, sleep=sleeps.append)
    except PipelineDBError as exc:
        error = str(exc)
    finally:
        broken.close()
        db.configure(good_url)
    cls = classify_mod.classify(attempt)
    pol = policy_mod.decide(cls.failure_class, has_token=bool(attempt.has_token), classification=cls)
    r.traces.append(Trace("outage delivery (nothing could be written; what the pipeline computed in memory)", [
        ("classify", f"{cls.failure_class.value} ({cls.source}): computed in memory, never written"),
        ("policy", f"{pol.action.value} in {human_delay(pol.delay_seconds)}: computed in memory, never written"),
        ("persist", f"decision commit REFUSED -> {error}"),
    ]))
    r.check(error is not None and error.startswith("event not acknowledged"), f"PipelineDBError raised: {error}")
    r.check(fx.calls == [] and fx.links() == [], "zero Razorpay calls, zero links during the outage")

    s3 = db.session()
    try:
        a = s3.get(PaymentAttempt, attempt_id)
        r.check(a is not None and _decisions(s3, attempt_id) == [] and _jobs(s3, attempt_id) == [],
                "after the outage the healthy database holds the ingested event and nothing else: no half-written decision or job")
        s = process_attempt(s3, a, execute_now=True, now=T0 + timedelta(minutes=5), rz_client=rz, llm_client=lm,
                            sleep=sleeps.append)
        r.traces.append(Trace("redelivery once the database is back", _trail(s3, attempt_id)))
        r.check(s["job_status"] == "sent" and s["duplicate"] is False and len(fx.links()) == 1,
                "redelivery: processed once, one link created, no skipped_duplicate (the outage delivery never reached the key)")
        crashed = _probe_crash_after_send(r, s3, fx, rz, lm, sleeps)
        lost = _probe_lost_response(r, s3, fx, lm, sleeps)
    finally:
        s3.close()

    r.fallback = ("PipelineDBError before any outbound call (event NOT acknowledged -> source redelivers); "
                  "after recovery the redelivery is processed once; a lost 'sent' write and a lost HTTP answer are "
                  "both resolved by reference_id lookup: the existing link is recorded, never re-created")
    r.final_state = ("outage delivery: PipelineDBError, 0 rows written, 0 Razorpay calls; "
                     f"redelivery: job#{s['job_id']} sent {s['link_url']}, links=1; "
                     f"crash-after-send probe: job#{crashed.id} sent {crashed.razorpay_link_url} (recovered by lookup); "
                     f"lost-response probe: job#{lost.id} sent {lost.razorpay_link_url} (reconciled, no follow-up); "
                     "still one link per payment")
    r.summary = "not acked, 0 calls; redelivery ok"


