def scenario_llm(r: Result, session, sleeps: list) -> None:
    """The two call sites, both degraded: classification of an unmapped event (-> human queue) and
    the customer nudge for a rules-classified link event (-> template). The link is still created."""
    fault = r.fault
    lm = llm.get_client()
    r.check(isinstance(lm, llm.FaultingLLM) and lm.fault == fault,
            f"llm.get_client() resolves FaultingLLM({fault}): faults beat API keys, nothing reaches the network")
    rz = razorpay_client.get_client()
    fx = razorpay_client.fixture()

    ev = _event(FailureClass.UNKNOWN, UNMAPPED_EVENT_INDEX[fault])
    r.events.append("unmapped event: " + _describe_event(ev))
    s = _deliver(session, ev, now=T0, rz=rz, lm=lm, sleeps=sleeps)
    classify_calls = len(lm.calls)
    trail = _trail(session, s["attempt_id"])
    r.traces.append(Trace("unmapped event", trail))
    d = _decisions(session, s["attempt_id"])[-1]
    job = session.get(RecoveryJob, s["job_id"])
    o = _outcome(session, s["attempt_id"])

    r.check(any(st == "classify" and m.startswith(f"UNKNOWN (rules): {NO_RULE_MATCHED}") for st, m in trail),
            "rules classified the event UNKNOWN (no rule matched) before any model was asked")
    r.check(classify_calls == CLASSIFY_CALLS[fault],
            f"exactly {CLASSIFY_CALLS[fault]} model call(s) for classification ({CALLS_NOTE[fault]})")
    r.check(d.classified_by == "fallback" and d.fallback_taken == f"{fault}->human_queue",
            f"decision classified_by=fallback, fallback_taken={fault}->human_queue")
    r.check(d.failure_class == "UNKNOWN" and d.confidence == 0.0,
            "the rejected answer was not coerced into a class: UNKNOWN at confidence 0.0, which never clears the 0.7 gate")
    r.check(d.action == "human_queue" and job.status == "human_queue", "action human_queue; the job row is parked, not pending")
    r.check(d.llm_used is True and d.llm_model == f"faulting-{fault}",
            "the decision row records that a model was consulted, and which one, even though it failed")
    r.check(job.razorpay_link_id is None and fx.links() == [] and fx.calls == [], "zero payment links, zero Razorpay calls")
    r.check(o is not None and o.recovered is False and (o.note or "").startswith("human_queue"),
            "outcome recorded at decision time: not recovered, human_queue")

    ev2 = _event(FailureClass.HARD_DECLINE, 0)
    r.events.append("nudge probe (rules-classified, link + message): " + _describe_event(ev2))
    s2 = _deliver(session, ev2, now=T0, rz=rz, lm=lm, sleeps=sleeps)
    nudge_calls = len(lm.calls) - classify_calls
    trail2 = _trail(session, s2["attempt_id"])
    r.traces.append(Trace("nudge probe", trail2))
    job2 = session.get(RecoveryJob, s2["job_id"])
    nudge_msgs = [m for st, m in trail2 if st == "nudge"]
    expected = NUDGE_FALLBACK[fault]
    r.check(s2["job_status"] == "sent" and len(fx.links()) == 1,
            "nudge probe: the link was created before the message was drafted; message generation never blocks a recovery")
    r.check(job2.nudge_source == "template" and bool(nudge_msgs) and f"(fallback: {expected})" in nudge_msgs[0],
            f"nudge probe: message drafted from the per-class template, audit row names the fallback {expected}")
    r.check(nudge_calls == NUDGE_CALLS[fault], f"nudge probe: exactly {NUDGE_CALLS[fault]} model call(s) for the message")
    r.check((job2.razorpay_link_url or "") in (job2.nudge_body or "") and format_rupees(ev2["amount_paise"]) in (job2.nudge_body or ""),
            "nudge probe: the template carries the real short_url and the exact amount")

    r.fallback = f"classification: {fault}->human_queue (a person decides); nudge: {expected} (per-class template)"
    r.final_state = (f"unmapped event: job#{job.id} human_queue, links=0, outcome=not recovered (human_queue); "
                     f"nudge probe: job#{job2.id} sent {job2.razorpay_link_url}, nudge=template [{expected}], links=1 (its own)")
    r.summary = "human_queue, 0 links; nudge from template"


def scenario_razorpay_429(r: Result, session, sleeps: list) -> None:
    rz = razorpay_client.get_client()
    fx = razorpay_client.fixture()
    r.check(isinstance(rz, FaultingRazorpayClient) and rz.fault == "razorpay_429" and rz.inner is fx,
            "razorpay_client.get_client() resolves the faulting wrapper around the in-memory fixture")
    lm = llm.get_client()
    ev = _event(FailureClass.HARD_DECLINE, 1)  # delay 0: executes on its own, no execute_now needed
    r.events.append(_describe_event(ev))
    s = _deliver(session, ev, now=T0, rz=rz, lm=lm, sleeps=sleeps, execute_now=False)
    rows = _audit_rows(session, s["attempt_id"])
    r.traces.append(Trace("event", [(x.stage, x.message) for x in rows]))
    job = session.get(RecoveryJob, s["job_id"])
    backoffs = [x for x in rows if x.stage == "execute" and "backing off" in x.message]
    sent = [x for x in rows if x.stage == "execute" and x.message.startswith("sent: payment link")]
    sent_client = json.loads(sent[0].data_json).get("client") if sent and sent[0].data_json else None

    r.check(job.status == "sent" and job.razorpay_link_id is not None, "job status sent with a link id")
    r.check(job.attempts_made == 3 and rz.create_calls == 3,
            "attempts_made == 3 (two 429s, then success); the client saw exactly 3 create calls")
    r.check(len(fx.links()) == 1 and fx.links()[0]["id"] == job.razorpay_link_id,
            "exactly one payment link exists at the fixture, and it is the job's")
    r.check(sleeps == [0.5, 1.0], f"exponential backoff 0.5s then 1.0s, no sleep after the final attempt (recorded, not waited): {sleeps}")
    r.check(len(backoffs) == 2, "two 'backing off' audit rows carry the HTTP status and the wait")
    r.check(sent_client == "fault:razorpay_429", "the 'sent' audit row names the client that answered (fault:razorpay_429)")
    r.check(fx.links()[0]["reference_id"] == job.idempotency_key[:40],
            "the link's reference_id is the idempotency key (first 40 chars): a retry after a crash would collide there too")
    r.check(job.nudge_source == "template" and (job.razorpay_link_url or "") in (job.nudge_body or ""),
            "nudge drafted after the link exists, with the real short_url")

    # A max_attempts=1 class throttled on every attempt: the recovery never reached the customer, so
    # it must be parked for a person, not closed "no_action: max attempts reached" (a rate limit is a
    # delivery failure, not an exhausted recovery).
    class _Always429:
        name = "always-429"

        def create_payment_link(self, payload):
            raise RazorpayError(429, "BAD_REQUEST_ERROR", "Too many requests")

        def fetch_payment_link(self, link_id):
            raise AssertionError("never fetched")

        def list_payment_links(self, *, reference_id):
            return []

    ev2 = _event(FailureClass.HARD_DECLINE, 2)
    r.events.append("delivery-exhausted probe (max_attempts=1, throttled on every attempt): " + _describe_event(ev2))
    s2 = _deliver(session, ev2, now=T0, rz=_Always429(), lm=lm, sleeps=sleeps, execute_now=True)
    job2 = session.get(RecoveryJob, s2["job_id"])
    follow = session.get(RecoveryJob, s2["followup_job_id"]) if s2["followup_job_id"] else None
    o2 = _outcome(session, s2["attempt_id"])
    r.traces.append(Trace("delivery-exhausted probe (max_attempts=1 throttled on every send)",
                          _trail(session, s2["attempt_id"])))
    r.check(job2.status == "failed" and executor.failure_kind(job2) == executor.RATE_LIMITED and job2.attempts_made == 3,
            "delivery-exhausted probe: the only send was rate-limited on all 3 attempts (kind rate_limited), no link")
    r.check(follow is not None and follow.status == "human_queue",
            "delivery-exhausted probe: parked human_queue, not closed 'no_action: max attempts reached'")
    r.check(o2 is not None and not o2.recovered and (o2.note or "").startswith("human_queue") and "throttled" in (o2.note or ""),
            "delivery-exhausted probe: the outcome records the throttle, so a rate limit is not mistaken for recovery exhausted")

    r.fallback = ("bounded exponential backoff on 429 (0.5s, 1.0s), then success on attempt 3 of 3; a max_attempts=1 "
                  "class throttled on every attempt is parked for a person, not closed as recovery exhausted")
    r.final_state = (f"job#{job.id} sent {job.razorpay_link_url}, attempts_made=3, links=1, outcome=open; "
                     f"delivery-exhausted probe: job#{job2.id} failed (rate_limited), follow-up job#{follow.id} human_queue")
    r.summary = "sent after 2 backoffs, 1 link"


